import { useState } from 'react';
import { ChevronDown, ChevronUp, FileWarning } from 'lucide-react';

import type { MessageFile, MessageImage } from '@agent/core/types';
import { fileContentUrl } from '@/features/files/files-api';
import { formatFileSize, ImagePreview } from './attachment-list';
import { FileTypeIcon } from './file-type-icon';

/** Past this many attachments the stack starts folded, so one long message cannot push the reply away. */
const COLLAPSE_THRESHOLD = 3;

/**
 * Sent images and documents sit above the user's bubble rather than inside it, matching the
 * composer's attachment cards. Files generated by a reply use their own card below the text.
 */
export function MessageAttachments({ images = [], files = [], fileIds = [] }: {
  images?: MessageImage[];
  files?: MessageFile[];
  /** Ids recorded on the message; an id with no metadata means the file was deleted. */
  fileIds?: string[];
}) {
  const [previewId, setPreviewId] = useState<string | null>(null);
  const total = images.length + files.length;
  // Folded for long stacks, open for the common case; the fold stays until the reader unfolds it.
  const [expanded, setExpanded] = useState(total <= COLLAPSE_THRESHOLD);
  const preview = images.find((image) => image.id === previewId);
  const foldable = total > COLLAPSE_THRESHOLD;
  const sizes = [...images.map((image) => image.size), ...files.map((file) => file.size)];
  const totalSize = sizes.every((size) => size != null) ? sizes.reduce((sum, size) => sum + (size ?? 0), 0) : null;
  const present = new Set([...images.flatMap((image) => image.fileId ? [image.fileId] : []), ...files.map((file) => file.id)]);
  const missing = [...new Set(fileIds)].filter((id) => !present.has(id));

  const cards = <div className="message-attachment-grid" role="list">
    {images.map((image) => {
      const source = image.dataUrl || (image.fileId ? fileContentUrl(image.fileId) : '');
      return <div className="composer-attachment message-attachment" key={image.id} title={image.name} role="listitem">
        <div className="attachment-artwork is-image">
          <button className="attachment-preview-trigger" type="button" aria-label={`预览图片 ${image.name}`} onClick={() => setPreviewId(image.id)}>
            <img src={source} alt="" />
          </button>
        </div>
        <span className="attachment-copy">
          <span className="attachment-name" title={image.name}>{image.name}</span>
          {image.size != null && <span className="attachment-meta">{formatFileSize(image.size)}</span>}
        </span>
      </div>;
    })}
    {files.map((file) => <a className="composer-attachment message-attachment is-document" key={file.id}
      title={file.filename} role="listitem" href={fileContentUrl(file.id)} download={file.filename}>
      <div className="attachment-artwork"><FileTypeIcon file={{ name: file.filename, type: file.contentType }} /></div>
      <span className="attachment-copy">
        <span className="attachment-name" title={file.filename}>{file.filename}</span>
        <span className="attachment-meta">{formatFileSize(file.size)}</span>
      </span>
    </a>)}
    {missing.map((id) => <div className="composer-attachment message-attachment is-missing" key={id} role="listitem">
      <div className="attachment-artwork"><FileWarning size={20} strokeWidth={1.6} aria-hidden="true" /></div>
      <span className="attachment-copy"><span className="attachment-name">文件已删除</span></span>
    </div>)}
  </div>;

  return <>
    <div className="message-attachments" aria-label="已发送的附件">
      {foldable && <div className="message-attachments-header">
        <span className="message-attachments-label">已发送的附件</span>
        {foldable && <button className="message-attachments-toggle" type="button" aria-expanded={expanded} onClick={() => setExpanded((open) => !open)}>
          <span>{total} 个文件{totalSize != null ? ` · ${formatFileSize(totalSize)}` : ''}</span>
          {expanded ? <ChevronUp size={14} strokeWidth={1.75} aria-hidden="true" /> : <ChevronDown size={14} strokeWidth={1.75} aria-hidden="true" />}
        </button>}
      </div>}
      {(!foldable || expanded) && cards}
    </div>
    {preview && <ImagePreview src={preview.dataUrl || (preview.fileId ? fileContentUrl(preview.fileId) : '')} name={preview.name} onClose={() => setPreviewId(null)} />}
  </>;
}
